# Rebuilds config/ozon_route_mix.yml: where our Ozon units really travel, by fulfilment (fbo / fbs) and buyer
# market (ru / by). Ec::LogisticsFormula weights Ozon's route tariff with it instead of averaging all 820 routes
# (a route nobody ships on counted as much as Moscow -> Moscow). The formula takes the simple average of the TOP_ROUTES
# busiest routes of a fulfilment and market; the shares in the file only rank the routes.
#
#   bin/rails runner script/generate_ozon_route_mix.rb            # prints the summary, writes the file
#   bin/rails runner script/generate_ozon_route_mix.rb --dry-run  # prints only
#   OZON_ROUTE_MIX_PRINT=1 ...                                    # prints the YAML instead of writing it
#
# Source: delivered-or-in-flight Ozon fulfilments of the last WEEKS full weeks (ec_order_fulfillments.cluster_from
# -> cluster_to, units from ec_order_items). The buyer market comes from the destination cluster's country in Ozon's
# own cluster table (the two clusters it does not list are in config/buyer_places.yml); a destination in another
# country (Kazakhstan, Armenia, ...) belongs to no scenario and is left out. Routes with fewer than MIN_UNITS units
# are dropped and the rest renormalised to shares that add up to 1.
dry_run = ARGV.include?("--dry-run")
print_yaml = ENV["OZON_ROUTE_MIX_PRINT"].present?
WEEKS = 12
MIN_UNITS = 3
TOP_ROUTES = { "fbo" => 40, "fbs" => 20 }.freeze
CONFIG_PATH = Rails.root.join("config/ozon_route_mix.yml")

period_to = Date.current.beginning_of_week(:monday)
period_from = period_to - WEEKS * 7
zone = ActiveSupport::TimeZone["Asia/Shanghai"]
from_time = zone.local(period_from.year, period_from.month, period_from.day).utc
to_time = zone.local(period_to.year, period_to.month, period_to.day).utc

countries = RawOzon::WarehouseCluster.distinct.pluck(:cluster_name, :country_name).to_h
overrides = (YAML.load_file(Rails.root.join("config/buyer_places.yml")).fetch("clusters", {}) rescue {})
market_of = lambda do |cluster|
  country = countries[cluster]
  country = "Россия" if country.blank? && overrides[cluster] == "RU"
  { "Россия" => "ru", "Беларусь" => "by" }[country]
end

sql = <<~SQL
  SELECT f.fulfillment_type AS mode, f.cluster_from AS origin, f.cluster_to AS destination, SUM(i.quantity) AS units
  FROM ec_order_fulfillments f
  JOIN ec_order_items i ON i.fulfillment_id = f.id
  JOIN ec_orders o ON o.id = f.order_id
  WHERE f.platform = 'ozon' AND f.fulfillment_type IN ('fbo', 'fbs')
    AND f.cluster_from IS NOT NULL AND f.cluster_to IS NOT NULL
    AND o.ordered_at >= '#{from_time.strftime('%Y-%m-%d %H:%M:%S')}' AND o.ordered_at < '#{to_time.strftime('%Y-%m-%d %H:%M:%S')}'
  GROUP BY 1, 2, 3
SQL
rows = ActiveRecord::Base.connection.select_all(sql).to_a

mix = {}
rows.group_by { |row| [ row["mode"], market_of.call(row["destination"]) ] }.each do |(mode, market), group|
  next unless market

  kept = group.select { |row| row["units"].to_i >= MIN_UNITS }
  total = kept.sum { |row| row["units"].to_i }
  next if total.zero?

  by_origin = kept.group_by { |row| row["origin"] }.sort_by { |_, list| -list.sum { |row| row["units"].to_i } }
  mix[mode] ||= {}
  mix[mode][market] = by_origin.to_h do |origin, list|
    [ origin, list.sort_by { |row| -row["units"].to_i }.to_h { |row| [ row["destination"], (row["units"].to_f / total).round(6) ] } ]
  end
  puts "#{mode}/#{market}: #{total} units on #{kept.size} routes from #{by_origin.size} origins (dropped #{group.size - kept.size} routes under #{MIN_UNITS} units)"
end

header = <<~TEXT
  # Where our Ozon units travel (origin cluster -> destination cluster), as shares of the units of the same
  # fulfilment and buyer market: #{period_from}..#{period_to - 1} (#{WEEKS} full weeks). Generated by
  # script/generate_ozon_route_mix.rb. top_routes: how many of the busiest routes (by share) Ec::LogisticsFormula averages.
TEXT
yaml = header + { "top_routes" => TOP_ROUTES }.merge(mix).to_yaml.sub(/\A---\n/, "")

if print_yaml
  puts yaml
elsif !dry_run
  File.write(CONFIG_PATH, yaml)
  puts "wrote #{CONFIG_PATH}"
end
