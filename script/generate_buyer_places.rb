# Rebuilds the "cities" section of config/buyer_places.yml from what Ozon itself says: every posting
# whose destination cluster is in a known country says that country for the buyer's city. A city seen
# in two countries is written as a list (a name that exists on both sides, like Дзержинск).
#
#   bin/rails runner script/generate_buyer_places.rb            # prints the summary, writes the file
#   bin/rails runner script/generate_buyer_places.rb --dry-run  # prints only
#
# Review the diff before committing: the file is the reviewed list of places, and a city that is not in it
# stays unknown (the order falls back to the currency) instead of being guessed.
dry_run = ARGV.include?("--dry-run")
table_countries = RawOzon::WarehouseCluster.distinct.pluck(:cluster_name, :country_name).to_h

seen = Hash.new { |hash, key| hash[key] = Hash.new(0) }
Ec::OrderFulfillment.where(platform: "ozon").where.not(cluster_to: nil).includes(:order).find_each do |fulfillment|
  country = Ec::BuyerCountry.ozon_cluster(fulfillment.cluster_to, table_countries)&.country or next
  places = [ fulfillment.order&.buyer_city ]
  places += RawOzon::PostingDestination.where(posting_number: fulfillment.external_fulfillment_id).pluck(:city)
  places.map { |place| Ec::BuyerCountry.normalize_place(place) }.reject(&:blank?).uniq.each { |key| seen[key][country] += 1 }
end

cities = seen.sort.to_h { |key, countries| [ key, countries.size == 1 ? countries.keys.first : countries.keys.sort ] }
ambiguous = cities.select { |_, value| value.is_a?(Array) }
puts "#{cities.size} places, #{ambiguous.size} on both sides of a border: #{ambiguous.keys.first(12).join(', ')}"
puts cities.values.flatten.tally.sort_by { |_, count| -count }.map { |code, count| "#{code}=#{count}" }.join("  ")

unless dry_run
  existing = File.exist?(Ec::BuyerCountry::CONFIG_PATH) ? YAML.load_file(Ec::BuyerCountry::CONFIG_PATH) : {}
  settings = existing.fetch("settings", { "currency_fallback" => true, "currency_countries" => { "BYN" => "BY", "RUB" => "RU" } })
  clusters = existing.fetch("clusters", {})
  header = <<~TEXT
    # Places (lower case, normalised by Ec::BuyerCountry.normalize_place) and their country, for orders
    # whose Ozon cluster is missing. Generated by script/generate_buyer_places.rb from the clusters Ozon
    # gives; a list means the same name exists in several countries. A place that is not here is unknown.
    #
    # clusters: Ozon destination clusters its own cluster table does not give a country for (reviewed by hand).
    #
    # currency_fallback: the last resort for an order with no cluster and no known place: the currency the
    # buyer paid in. Set it to false (and the orders without a place go unresolved) as soon as another
    # market bills in one of these currencies.
  TEXT
  File.write(Ec::BuyerCountry::CONFIG_PATH, header + { "settings" => settings, "clusters" => clusters, "cities" => cities }.to_yaml.sub(/\A---\n/, ""))
  puts "wrote #{Ec::BuyerCountry::CONFIG_PATH}"
end
